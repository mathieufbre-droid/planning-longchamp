-- =====================================================================
-- Planning familial de l'appartement de Saint François Longchamps
--   * membres invités par l'administrateur, inactifs tant qu'il ne les a pas activés
--   * deux rôles : ADMINISTRATEUR (gère réservations et membres), LECTEUR (lecture seule)
--   * réservations sans chevauchement, garanties par la base (contrainte d'exclusion)
-- =====================================================================

CREATE TYPE role_membre AS ENUM ('ADMINISTRATEUR', 'LECTEUR');
CREATE TYPE type_reservation AS ENUM ('SEMAINE', 'WEEK_END', 'AUTRE');

-- ---------- Membres ----------
CREATE TABLE membres (
    id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL PRIMARY KEY,
    nom TEXT NOT NULL DEFAULT '',
    prenom TEXT NOT NULL DEFAULT '',
    email TEXT UNIQUE NOT NULL,
    role role_membre NOT NULL DEFAULT 'LECTEUR',
    actif BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION public.est_actif()
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT EXISTS (SELECT 1 FROM membres WHERE id = auth.uid() AND actif)
$$;

CREATE OR REPLACE FUNCTION public.est_admin()
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT EXISTS (SELECT 1 FROM membres WHERE id = auth.uid() AND actif AND role = 'ADMINISTRATEUR')
$$;

-- Profil créé automatiquement quand un compte est invité depuis Supabase
CREATE OR REPLACE FUNCTION public.creer_profil_membre()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    INSERT INTO membres (id, nom, prenom, email)
    VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'nom', ''),
            COALESCE(NEW.raw_user_meta_data->>'prenom', ''), NEW.email);
    RETURN NEW;
END $$;

CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.creer_profil_membre();

-- Il reste toujours au moins un administrateur actif (sinon plus personne ne peut gérer)
CREATE OR REPLACE FUNCTION public.garder_un_administrateur()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF OLD.role = 'ADMINISTRATEUR' AND OLD.actif
       AND (TG_OP = 'DELETE' OR NEW.role <> 'ADMINISTRATEUR' OR NOT NEW.actif)
       AND NOT EXISTS (SELECT 1 FROM membres WHERE id <> OLD.id AND actif AND role = 'ADMINISTRATEUR') THEN
        RAISE EXCEPTION 'Il doit rester au moins un administrateur actif.';
    END IF;
    RETURN COALESCE(NEW, OLD);
END $$;

CREATE TRIGGER membres_garder_admin
    BEFORE UPDATE OR DELETE ON membres
    FOR EACH ROW EXECUTE FUNCTION public.garder_un_administrateur();

-- ---------- Réservations ----------
-- Une réservation occupe les nuits de « arrivee » (incluse) à « depart » (exclu) :
-- un départ le samedi et une arrivée le même samedi ne se chevauchent pas.
CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arrivee DATE NOT NULL,
    depart DATE NOT NULL,
    type type_reservation NOT NULL DEFAULT 'AUTRE',
    occupant TEXT NOT NULL CHECK (btrim(occupant) <> ''),
    note TEXT NOT NULL DEFAULT '',
    cree_par UUID REFERENCES membres(id) ON DELETE SET NULL DEFAULT auth.uid(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT reservations_dates CHECK (depart > arrivee AND depart - arrivee <= 62),
    CONSTRAINT reservations_sans_chevauchement
        EXCLUDE USING gist (daterange(arrivee, depart, '[)') WITH &&)
);

CREATE INDEX reservations_arrivee_idx ON reservations (arrivee);

CREATE OR REPLACE FUNCTION public.horodater_reservation()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := NOW();
    NEW.cree_par := OLD.cree_par;
    RETURN NEW;
END $$;

CREATE TRIGGER reservations_horodatage
    BEFORE UPDATE ON reservations
    FOR EACH ROW EXECUTE FUNCTION public.horodater_reservation();

-- ---------- Row Level Security ----------
ALTER TABLE membres ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservations ENABLE ROW LEVEL SECURITY;

-- Membres : chacun voit son profil, les membres actifs voient la famille, seul l'admin modifie.
CREATE POLICY "Lecture des membres" ON membres FOR SELECT USING (id = auth.uid() OR est_actif());
CREATE POLICY "Admin modifie les membres" ON membres FOR UPDATE USING (est_admin()) WITH CHECK (est_admin());
CREATE POLICY "Admin supprime les membres" ON membres FOR DELETE USING (est_admin() AND id <> auth.uid());

-- Réservations : lecture pour tout membre actif, écriture réservée aux administrateurs.
CREATE POLICY "Lecture des réservations" ON reservations FOR SELECT USING (est_actif());
CREATE POLICY "Admin crée les réservations" ON reservations FOR INSERT WITH CHECK (est_admin());
CREATE POLICY "Admin modifie les réservations" ON reservations FOR UPDATE USING (est_admin()) WITH CHECK (est_admin());
CREATE POLICY "Admin supprime les réservations" ON reservations FOR DELETE USING (est_admin());

GRANT SELECT, UPDATE, DELETE ON membres TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON reservations TO authenticated;
